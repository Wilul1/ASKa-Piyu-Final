"""Create a development-only student test account.

This does not change public signup or campus invite-code validation.
It inserts (or updates) one student row through the same User model and
password hasher the rest of the app uses.

Run from the backend directory:

    python scripts/seed_student_test_account.py
    python scripts/seed_student_test_account.py --force-reset-password

Password sources, in order:
  1. --password
  2. ASKA_SEED_STUDENT_PASSWORD
  3. a generated secret, written to backend/.local/student_test_account.txt
     (gitignored; never printed)

The script refuses to run when ASKA_ENV is production.
"""

from __future__ import annotations

import argparse
import os
import re
import secrets
import stat
import sys
from pathlib import Path

_BACKEND_ROOT = Path(__file__).resolve().parents[1]
if str(_BACKEND_ROOT) not in sys.path:
    sys.path.insert(0, str(_BACKEND_ROOT))

from app.config import BACKEND_DIR, settings
from app.db.session import get_session_factory, initialize_database
from app.models.db_models import User
from app.services.passwords import hash_password, verify_password

DEFAULT_EMAIL = "student@aska.local"
DEFAULT_NAME = "ASKa Student Tester"
CREDENTIALS_PATH = BACKEND_DIR / ".local" / "student_test_account.txt"


def _is_production() -> bool:
    return settings.env.strip().lower() in {"production", "prod"}


def _validate_password(password: str) -> None:
    if len(password) < 10:
        raise SystemExit("ERROR: Student test password must be at least 10 characters.")
    if not re.search(r"[A-Za-z]", password) or not re.search(r"\d", password):
        raise SystemExit("ERROR: Student test password must include a letter and a digit.")


def _generate_password() -> str:
    # token_urlsafe is not guaranteed to include a digit; append a mix the
    # existing signup policy accepts, without using a memorable default.
    return secrets.token_urlsafe(18) + "A1"


def _write_credentials_file(email: str, password: str) -> Path:
    CREDENTIALS_PATH.parent.mkdir(parents=True, exist_ok=True)
    payload = (
        "# Development-only ASKa-Piyu student test account.\n"
        "# Generated by scripts/seed_student_test_account.py. Do not commit.\n"
        f"email={email}\n"
        f"password={password}\n"
    )
    CREDENTIALS_PATH.write_text(payload, encoding="utf-8")
    try:
        os.chmod(CREDENTIALS_PATH, stat.S_IRUSR | stat.S_IWUSR)
    except OSError:
        # Windows may ignore POSIX mode bits; the gitignore still keeps the file local.
        pass
    return CREDENTIALS_PATH


def _resolve_password(cli_password: str) -> tuple[str, bool]:
    """Return (password, generated)."""
    password = (cli_password or os.getenv("ASKA_SEED_STUDENT_PASSWORD") or "").strip()
    if password:
        return password, False
    return _generate_password(), True


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Seed a development-only student test account.",
    )
    parser.add_argument(
        "--email",
        default=(os.getenv("ASKA_SEED_STUDENT_EMAIL") or DEFAULT_EMAIL).strip() or DEFAULT_EMAIL,
    )
    parser.add_argument(
        "--password",
        default="",
        help="Optional. Otherwise ASKA_SEED_STUDENT_PASSWORD, else a generated secret.",
    )
    parser.add_argument(
        "--name",
        default=(os.getenv("ASKA_SEED_STUDENT_NAME") or DEFAULT_NAME).strip() or DEFAULT_NAME,
    )
    parser.add_argument(
        "--force-reset-password",
        action="store_true",
        help="If the student email already exists, reset its password and keep role=student.",
    )
    args = parser.parse_args()

    if _is_production():
        raise SystemExit(
            "ERROR: Refusing to seed a student test account while ASKA_ENV is production."
        )

    email = args.email.strip().lower()
    if not email or "@" not in email:
        raise SystemExit("ERROR: Set ASKA_SEED_STUDENT_EMAIL or pass --email.")

    password, generated = _resolve_password(args.password)
    _validate_password(password)

    if settings.database_init_on_startup or settings.env != "production":
        initialize_database()

    session = get_session_factory()()
    try:
        existing = session.query(User).filter(User.email == email).first()
        if existing is not None:
            if existing.role != "student":
                raise SystemExit(
                    f"ERROR: {email} exists with role={existing.role}. "
                    "The student seed will not change a non-student account."
                )
            if not args.force_reset_password:
                print(f"Student test account already exists: {email} (id={existing.id})")
                print("Use --force-reset-password to rotate the password.")
                return
            existing.role = "student"
            existing.office_id = None
            existing.full_name = args.name
            existing.password_hash = hash_password(password)
            existing.is_active = True
            existing.email_verified = True
            existing.email_verification_code_hash = None
            existing.email_verification_expires_at = None
            existing.credentials_version = int(existing.credentials_version or 0) + 1
            session.commit()
            credentials_path = _write_credentials_file(email, password)
            print(f"Updated student test account: {email}")
            if generated:
                print(f"Generated password written to {credentials_path}")
            else:
                print(f"Password recorded at {credentials_path}")
            return

        user = User(
            email=email,
            password_hash=hash_password(password),
            full_name=args.name,
            role="student",
            is_active=True,
            email_verified=True,
        )
        if not verify_password(password, user.password_hash):
            raise SystemExit("ERROR: Password hash round-trip failed.")
        session.add(user)
        session.commit()
        session.refresh(user)
        credentials_path = _write_credentials_file(email, password)
        print(f"Created student test account: {email} (id={user.id})")
        print("Role=student, is_active=true, email_verified=true (development seed).")
        if generated:
            print(f"Generated password written to {credentials_path}")
        else:
            print(f"Password recorded at {credentials_path}")
    finally:
        session.close()


if __name__ == "__main__":
    main()
